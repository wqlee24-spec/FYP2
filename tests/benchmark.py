"""Performance benchmark harness — Hybrid Security Suite (FYP2 Future Work #5).

Runs a condition x load matrix and writes a CSV plus a summary table, so the
evaluation chapter can be regenerated by re-running one command.

    python tests/benchmark.py                    # full matrix
    python tests/benchmark.py --quick            # fast smoke run
    python tests/benchmark.py --reps 30          # publication-quality

CONDITIONS
    baseline  workload only, no agent and no detector  -> cost of the I/O itself
    heur      agent with --no-etw                      -> FYP1 attribution path
    etw       agent with ETW enabled                   -> FYP2 attribution path

The heur/etw pair is the controlled A/B: it isolates what ETW attribution costs
and what accuracy it buys, with everything else held constant.

METRICS (per cell)
    achieved_rate_ops_s   real throughput (never assume the target was met)
    loss_pct              files created but never seen by the detector
    agent_cpu_* / rss     C++ monitor agent overhead
    py_cpu_* / rss        Python controller overhead
    lat_p50/p95/max_ms    file written -> detector received the event
    etw_events/heur_events  attribution split

METHOD NOTES (state these in the report)
  * CPU is normalised by core count, so 100% == all cores saturated.
  * Latency uses time.time_ns() on both sides: it is wall-clock, so it stays
    comparable across the generator and the detector process.
  * The first `warmup` reps of each cell are discarded (disk cache effects).
  * Containment is stubbed - the harness never applies a real ACL.
  * EXCLUDE the watch directory from Windows Defender before running, or you are
    largely measuring Defender's real-time scanner. Record which you did.
"""

import argparse
import csv
import os
import statistics
import subprocess
import sys
import tempfile
import threading
import time

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import main_latesttt as m

try:
    import psutil
except ImportError:
    psutil = None

SRC = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
AGENT = os.path.join(SRC, "monitor_agent.exe")
NCPU = (psutil.cpu_count() or 1) if psutil else 1


# ── Resource sampling ────────────────────────────────────────────────────────
class ResourceSampler(threading.Thread):
    """Polls CPU% and RSS for the agent and this Python process."""

    def __init__(self, agent_pid, interval=0.25):
        super().__init__(daemon=True)
        self._interval = interval
        self._stop = threading.Event()
        self.agent_cpu, self.agent_rss = [], []
        self.py_cpu, self.py_rss = [], []

        self._agent = None
        self._py = None
        if psutil:
            try:
                if agent_pid:
                    self._agent = psutil.Process(agent_pid)
                    self._agent.cpu_percent(None)      # seed
                self._py = psutil.Process(os.getpid())
                self._py.cpu_percent(None)
            except psutil.Error:
                pass

    def stop(self):
        self._stop.set()

    def run(self):
        while not self._stop.is_set():
            time.sleep(self._interval)
            for proc, cpu, rss in ((self._agent, self.agent_cpu, self.agent_rss),
                                   (self._py, self.py_cpu, self.py_rss)):
                if proc is None:
                    continue
                try:
                    cpu.append(proc.cpu_percent(None) / NCPU)
                    rss.append(proc.memory_info().rss / (1024 * 1024))
                except psutil.Error:
                    pass


# ── Load generation ──────────────────────────────────────────────────────────
def generate_load(watch_dir, n_files, target_rate, created):
    """Write n_files at ~target_rate ops/sec, recording a ns stamp per path."""
    delay = 1.0 / target_rate if target_rate > 0 else 0.0
    payload = b"x" * 4096
    start = time.perf_counter()
    for i in range(n_files):
        path = os.path.join(watch_dir, f"bench_{i:06d}.dat")
        try:
            with open(path, "wb") as fh:
                fh.write(payload)
            created[os.path.normcase(path)] = time.time_ns()
        except OSError:
            pass
        if delay:
            target_t = start + (i + 1) * delay
            now = time.perf_counter()
            if target_t > now:
                time.sleep(target_t - now)
    return time.perf_counter() - start


def pct(values, p):
    if not values:
        return 0.0
    values = sorted(values)
    k = (len(values) - 1) * (p / 100.0)
    lo, hi = int(k), min(int(k) + 1, len(values) - 1)
    return values[lo] + (values[hi] - values[lo]) * (k - lo)


# ── One cell of the matrix ───────────────────────────────────────────────────
def run_cell(condition, target_rate, n_files, watch_dir):
    for f in os.listdir(watch_dir):
        try: os.remove(os.path.join(watch_dir, f))
        except OSError: pass

    created = {}
    received = {}          # normcased path -> ns when the detector saw it
    sources = []
    alerts = []

    agent = None
    reader = None
    sampler = None
    tmpdb = os.path.join(tempfile.mkdtemp(prefix="hss_bench_"), "b.db")

    try:
        if condition != "baseline":
            cmd = [AGENT, "--watch-dir", watch_dir]
            if condition == "heur":
                cmd.append("--no-etw")
            agent = subprocess.Popen(cmd, stdout=subprocess.DEVNULL,
                                     stderr=subprocess.DEVNULL,
                                     creationflags=subprocess.CREATE_NO_WINDOW)
            time.sleep(1.2)

            db = m.Database(tmpdb)
            config = m.DetectionConfig(file_thresh=5, event_cap=10, window_secs=0.01)
            state = m.MonitoringState(active=True)
            # Containment stubbed: never touch real ACLs during benchmarking.
            det = m.RansomwareDetector(db, config, state,
                                       lambda pid, files: alerts.append(time.time_ns()) or "STUB")

            inner = det.record
            def instrumented(fp, pid, source="HEUR"):
                key = os.path.normcase(fp)
                if key not in received:
                    received[key] = time.time_ns()
                sources.append(source)
                return inner(fp, pid, source)
            det.record = instrumented

            reader = m.PipeReader(m.PIPE_NAME, det)
            reader.start()
            time.sleep(1.0)

        sampler = ResourceSampler(agent.pid if agent else None)
        sampler.start()

        elapsed = generate_load(watch_dir, n_files, target_rate, created)
        time.sleep(2.5)          # drain the pipe

    finally:
        if sampler: sampler.stop()
        if reader: reader.stop()
        if agent:
            try:
                agent.terminate(); agent.wait(timeout=5)
            except Exception:
                agent.kill()
        for f in os.listdir(watch_dir):
            try: os.remove(os.path.join(watch_dir, f))
            except OSError: pass

    lat_ms = [(received[k] - created[k]) / 1e6
              for k in created if k in received and received[k] >= created[k]]

    seen = len(set(received) & set(created))
    if condition == "baseline":
        # No detector exists in this condition, so "loss" is undefined rather
        # than 100% — reporting 100 here would look like catastrophic failure.
        loss = float("nan")
    else:
        loss = 100.0 * (1 - seen / len(created)) if created else 0.0

    mean = lambda v: statistics.fmean(v) if v else 0.0
    return {
        "condition": condition,
        "target_rate_ops_s": target_rate,
        "files": len(created),
        "achieved_rate_ops_s": round(len(created) / elapsed, 1) if elapsed else 0,
        "events_seen": seen,
        "loss_pct": round(loss, 2),
        "agent_cpu_mean_pct": round(mean(sampler.agent_cpu), 2) if sampler else 0,
        "agent_cpu_max_pct": round(max(sampler.agent_cpu), 2) if sampler and sampler.agent_cpu else 0,
        "agent_rss_mb": round(mean(sampler.agent_rss), 2) if sampler else 0,
        "py_cpu_mean_pct": round(mean(sampler.py_cpu), 2) if sampler else 0,
        "py_rss_mb": round(mean(sampler.py_rss), 2) if sampler else 0,
        "lat_p50_ms": round(pct(lat_ms, 50), 2),
        "lat_p95_ms": round(pct(lat_ms, 95), 2),
        "lat_max_ms": round(max(lat_ms), 2) if lat_ms else 0,
        "etw_events": sources.count("ETW"),
        "heur_events": sources.count("HEUR"),
        "alerts": len(alerts),
    }


def main():
    ap = argparse.ArgumentParser(description="Hybrid Security Suite benchmark")
    ap.add_argument("--reps", type=int, default=5, help="reps per cell (30 for publication)")
    ap.add_argument("--warmup", type=int, default=1, help="reps discarded per cell")
    ap.add_argument("--files", type=int, default=200, help="files written per rep")
    ap.add_argument("--quick", action="store_true", help="tiny smoke run")
    ap.add_argument("--out", default=os.path.join(SRC, "tests", "benchmark_results.csv"))
    args = ap.parse_args()

    try:
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    except Exception:
        pass

    if not os.path.exists(AGENT):
        print(f"ERROR: agent not found at {AGENT}")
        return 1
    if psutil is None:
        print("ERROR: psutil required (pip install psutil)")
        return 1

    rates = [50, 200] if args.quick else [10, 50, 100, 500, 1000]
    conditions = ["baseline", "heur", "etw"]
    reps = 2 if args.quick else args.reps
    warmup = 0 if args.quick else args.warmup
    n_files = 50 if args.quick else args.files

    elevated = False
    try:
        import ctypes
        elevated = bool(ctypes.windll.shell32.IsUserAnAdmin())
    except Exception:
        pass

    print("=" * 78)
    print("Hybrid Security Suite — performance benchmark")
    print("=" * 78)
    print(f"  cores={NCPU}  reps={reps} (+{warmup} warmup)  files/rep={n_files}")
    print(f"  rates={rates}  conditions={conditions}")
    print(f"  elevated={elevated}"
          f"{'' if elevated else '   <-- ETW WILL FALL BACK TO HEURISTIC; rerun as Admin'}")
    print("  NOTE: exclude the watch dir from Defender, or you are measuring Defender.\n")

    watch_dir = tempfile.mkdtemp(prefix="hss_watch_")
    rows = []
    try:
        for cond in conditions:
            for rate in rates:
                cells = []
                for r in range(reps + warmup):
                    res = run_cell(cond, rate, n_files, watch_dir)
                    if r >= warmup:
                        cells.append(res)
                    lp = res["loss_pct"]
                    loss_txt = "n/a" if lp != lp else f"{lp}%"     # NaN != NaN
                    print(f"  {cond:<9} {rate:>5}/s  rep {r+1}/{reps+warmup}  "
                          f"achieved={res['achieved_rate_ops_s']:>7}/s  "
                          f"loss={loss_txt:>6}  "
                          f"p50={res['lat_p50_ms']:>8}ms")
                if not cells:
                    continue
                agg = {"condition": cond, "target_rate_ops_s": rate, "reps": len(cells)}
                for key in cells[0]:
                    if key in ("condition", "target_rate_ops_s"):
                        continue
                    vals = [c[key] for c in cells if c[key] == c[key]]   # drop NaN
                    agg[key] = round(statistics.fmean(vals), 2) if vals else float("nan")
                rows.append(agg)
    finally:
        try:
            for f in os.listdir(watch_dir): os.remove(os.path.join(watch_dir, f))
            os.rmdir(watch_dir)
        except OSError:
            pass

    with open(args.out, "w", newline="", encoding="utf-8") as fh:
        w = csv.DictWriter(fh, fieldnames=list(rows[0].keys()))
        w.writeheader()
        w.writerows(rows)

    print("\n" + "=" * 78)
    print("SUMMARY  (CPU normalised by core count; 100% = all cores)")
    print("=" * 78)
    hdr = f"{'cond':<9}{'rate':>6}{'achieved':>10}{'loss%':>8}{'agentCPU':>10}{'agentMB':>9}{'pyCPU':>8}{'p50ms':>9}{'p95ms':>9}{'ETW':>7}"
    print(hdr); print("-" * len(hdr))
    for r in rows:
        print(f"{r['condition']:<9}{r['target_rate_ops_s']:>6}"
              f"{r['achieved_rate_ops_s']:>10}"
              f"{('n/a' if r['loss_pct'] != r['loss_pct'] else r['loss_pct']):>8}"
              f"{r['agent_cpu_mean_pct']:>10}{r['agent_rss_mb']:>9}"
              f"{r['py_cpu_mean_pct']:>8}{r['lat_p50_ms']:>9}{r['lat_p95_ms']:>9}"
              f"{int(r['etw_events']):>7}")

    print(f"\nCSV written to {args.out}")
    if not elevated:
        print("\nNOTE: not elevated — the 'etw' rows fell back to the heuristic, so the\n"
              "      ETW-vs-heuristic comparison is not valid. Re-run as Administrator.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
